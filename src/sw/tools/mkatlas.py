#!/usr/bin/env python3
"""The atlases of bt_tiles (rtl/video/bt_tiles.v) from atlas.py, and the tile codes for the C program.

  mkatlas.py ATLAS1.bin ATLAS4.bin atlas_gen.h

A tile whose coverages are only 0 and 15 goes to the 1-bit atlas (code = its index there), any other
to the 4-bit one (code = 0x200 + its index). Pixel n = row * 10 + column of tile t is bit / nibble
t * 200 + n of its atlas, the low bit / nibble of a byte first (as bt_tiles reads them)."""
import sys
from atlas import Atlas, BIG_CHARS

A1_MAX, A4_MAX = 8192 * 8 // 200, 4096 * 2 // 200   # the sizes of the RAMs in bt_tiles


def main(out1, out4, out_h):
    a = Atlas()
    n = a.cw * a.ch
    code, t1, t4 = [], [], []
    for data in a.tiles:
        if all(v in (0, 15) for v in data):
            code.append(len(t1)); t1.append(data)
        else:
            code.append(0x200 + len(t4)); t4.append(data)
    assert len(t1) <= A1_MAX and len(t4) <= A4_MAX, (len(t1), len(t4))
    b1 = bytearray((len(t1) * n + 7) // 8)
    for t, data in enumerate(t1):
        for i, v in enumerate(data):
            if v:
                k = t * n + i
                b1[k >> 3] |= 1 << (k & 7)
    b4 = bytearray((len(t4) * n + 1) // 2)
    for t, data in enumerate(t4):
        for i, v in enumerate(data):
            k = t * n + i
            b4[k >> 1] |= v << (4 * (k & 1))
    open(out1, "wb").write(b1)
    open(out4, "wb").write(b4)

    h = ["// generated by tools/mkatlas.py from tools/atlas.py: do not edit",
         "#pragma once", "#include <stdint.h>", "",
         f"// 1-bit tiles {len(t1)} of {A1_MAX}, 4-bit tiles {len(t4)} of {A4_MAX}"]
    for name, i in sorted(a.id.items()):
        if isinstance(i, int) and not name.startswith(("ch:", "big:")):
            h.append(f"#define T_{name.upper()} 0x{code[i]:03x}")
    h.append("// the font: the tile of character 32 + i")
    h.append("static const uint16_t t_font[95] = {")
    h.append("  " + ", ".join(f"0x{code[a.id['ch:' + chr(c)]]:03x}" for c in range(32, 127)) + " };")
    h.append(f'// the big characters "{BIG_CHARS}": 2 x 2 tiles each, left-top, right-top, left-bottom, right-bottom')
    h.append(f"#define BIG_CHARS \"{BIG_CHARS}\"")
    h.append(f"static const uint16_t t_big[{len(BIG_CHARS)}][4] = {{")
    for c in BIG_CHARS:
        h.append("  { " + ", ".join(f"0x{code[a.id[f'big:{c}:{k}']]:03x}" for k in range(4)) + " },")
    h.append("};")
    h.append("// the meter: k (0..10) columns filled")
    h.append(f"static const uint16_t t_bar[{a.cw + 1}] = {{ " + ", ".join(f"0x{code[a.id[f'bar{k}']]:03x}" for k in range(a.cw + 1)) + " };")
    cols, rows, idx = a.id["logo"]
    h.append(f"#define LOGO_COLS {cols}")
    h.append(f"#define LOGO_ROWS {rows}")
    h.append(f"static const uint16_t t_logo[{cols * rows}] = {{")
    for r in range(rows):
        h.append("  " + ", ".join(f"0x{code[i]:03x}" for i in idx[r * cols:(r + 1) * cols]) + ",")
    h.append("};")
    open(out_h, "w").write("\n".join(h) + "\n")
    print(f"atlas: {len(t1)} 1-bit tiles ({len(b1)} bytes), {len(t4)} 4-bit tiles ({len(b4)} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main(*sys.argv[1:4])
